// IsLauncherFullyInstalled checks if all launcher components exist for the given GPU type.
func IsLauncherFullyInstalled(gpuType, wineprefix string) bool {
	// Check binary
	if !IsLauncherInstalled(gpuType) {
		return false
	}

	// Check desktop file
	desktopPath := LauncherDesktopPath(gpuType)
	if _, err := os.Stat(desktopPath); err != nil {
		return false
	}

	// Check launch_vars.env
	if _, err := os.Stat(filepath.Join(wineprefix, "launch_vars.env")); err != nil {
		return false
	}

	// Check launcher executable
	if _, err := os.Stat(LauncherExePath(wineprefix)); err != nil {
		return false
	}

	return true
}

// DetectLauncherType detects whether the installed launcher is a wine or proton wrapper.
// Both GPU types use /usr/local/bin/Bellum — detection is by content.
func DetectLauncherType() string {
	bellumPath := "/usr/local/bin/Bellum"
	if exists, _ := fileExists(bellumPath); !exists {
		return ""
	}
	content, err := os.ReadFile(bellumPath)
	if err != nil {
		return ""
	}
	// AMD wrapper uses wineboot + wine
	if strings.Contains(string(content), "wineboot") {
		return "AMD"
	}
	// NVIDIA wrapper uses proton run
	if strings.Contains(string(content), "proton run") {
		return "NVIDIA"
	}
	return ""
}

func fileExists(path string) (bool, error) {
	_, err := os.Stat(path)
	if err == nil {
		return true, nil
	}
	if os.IsNotExist(err) {
		return false, nil
	}
	return false, err
}
