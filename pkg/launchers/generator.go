// writeWrapper writes a wrapper script to the specified path.
// If writing to /usr/local/bin/ and not running as root, it uses pkexec to elevate privileges.
func writeWrapper(path, content string) error {
	dir := filepath.Dir(path)

	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("failed to create directory %s: %w", dir, err)
	}

	// Check if we need elevated privileges
	if os.Geteuid() != 0 && strings.HasPrefix(path, "/usr/local/bin/") {
		return writeWrapperWithSudo(path, content)
	}

	if err := os.WriteFile(path, []byte(content), 0755); err != nil {
		return fmt.Errorf("failed to write wrapper script: %w", err)
	}

	return nil
}

// writeWrapperWithSudo uses pkexec to write the file with elevated privileges.
func writeWrapperWithSudo(path, content string) error {
	// Get the current user for ownership
	currentUser, err := user.Current()
	if err != nil {
		return fmt.Errorf("failed to get current user: %w", err)
	}

	// Create a temporary file with the content
	tmpFile, err := os.CreateTemp("", "bellum-launcher-*.sh")
	if err != nil {
		return fmt.Errorf("failed to create temporary file: %w", err)
	}
	tmpPath := tmpFile.Name()
	defer os.Remove(tmpPath) // Clean up temp file

	if _, err := tmpFile.WriteString(content); err != nil {
		tmpFile.Close()
		return fmt.Errorf("failed to write to temporary file: %w", err)
	}
	tmpFile.Close()

	// Use pkexec to copy the file to the target location with root privileges
	cmd := []string{"pkexec", "cp", tmpPath, path}
	if err := core.RunCommand(core.RunModeStream, cmd, nil, ""); err != nil {
		return fmt.Errorf("failed to copy launcher with pkexec: %w", err)
	}

	// Make the file executable
	cmd = []string{"pkexec", "chmod", "755", path}
	if err := core.RunCommand(core.RunModeStream, cmd, nil, ""); err != nil {
		return fmt.Errorf("failed to make launcher executable: %w", err)
	}

	// Change ownership to the current user
	chownArg := fmt.Sprintf("%s:%s", currentUser.Username, currentUser.Username)
	cmd = []string{"pkexec", "chown", chownArg, path}
	if err := core.RunCommand(core.RunModeStream, cmd, nil, ""); err != nil {
		return fmt.Errorf("failed to change launcher ownership: %w", err)
	}

	return nil
}

// generateDesktopFiles creates the .desktop files and icon for the launcher.
// Both GPU types use the same binary name "Bellum" and desktop file "Bellum.desktop".
// This mirrors the bash behavior in lib/launcher.sh:
//   - Desktop files go to ~/.local/share/applications/
//   - Desktop files are also copied to ~/Desktop/
//   - Icon goes to ~/.local/share/icons/hicolor/256x256/apps/bellum.png
//   - gio set metadata::trusted is applied if available
//   - update-desktop-database is run if available
func generateDesktopFiles(config LauncherConfig) error {
	homeDir, err := os.UserHomeDir()
	if err != nil {
		return fmt.Errorf("failed to get user home directory: %w", err)
	}

	appsDir := filepath.Join(homeDir, ".local", "share", "applications")
	appsIconDir := filepath.Join(homeDir, ".local", "share", "icons", "hicolor", "256x256", "apps")

	var entryComment string
	switch config.GPUType {
	case "AMD":
		entryComment = "Launch Bellum via Wine"
	case "NVIDIA":
		entryComment = "Launch Bellum via Proton (NVIDIA optimized)"
	default:
		return fmt.Errorf("unsupported GPU type for desktop file: %s", config.GPUType)
	}
	entryName := "Bellum"
	entryExec := "Bellum"

	// Install icon
	installedIcon := ""
	if config.IconPath != "" {
		if err := os.MkdirAll(appsIconDir, 0755); err != nil {
			return fmt.Errorf("failed to create icon directory: %w", err)
		}
		iconDest := filepath.Join(appsIconDir, "bellum.png")
		if err := copyFile(config.IconPath, iconDest); err != nil {
			return fmt.Errorf("failed to copy icon: %w", err)
		}
		installedIcon = filepath.Join(appsIconDir, "bellum.png")
	} else {
		// Fallback: no icon
		installedIcon = ""
	}

	// Generate .desktop file
	desktopFile := filepath.Join(appsDir, fmt.Sprintf("%s.desktop", entryName))
	desktopContent := fmt.Sprintf(`[Desktop Entry]
Name=%s
Comment=%s
Exec=%s
Icon=%s
Type=Application
Categories=Game;
Terminal=false
Path=%s
`, entryName, entryComment, entryExec, installedIcon, config.Wineprefix)

	if err := os.WriteFile(desktopFile, []byte(desktopContent), 0755); err != nil {
		return fmt.Errorf("failed to write desktop file %s: %w", desktopFile, err)
	}

	// Copy to ~/Desktop/
	desktopDest := filepath.Join(homeDir, "Desktop", fmt.Sprintf("%s.desktop", entryName))
	if _, err := os.Stat(filepath.Join(homeDir, "Desktop")); err == nil {
		if err := copyFile(desktopFile, desktopDest); err != nil {
			// Non-fatal: desktop directory may not exist or be inaccessible
		}
	}

	// Set write perm
	if err := os.Chmod(desktopDest, 0755); err != nil {
		return fmt.Errorf("failed to make Bellum desktop file executable: %w", err)
	}

	// Mark as trusted via gio if available
	if runtime.GOOS == "linux" {
		_ = runGioSet(desktopFile, "metadata::trusted", "true")
		if _, err := os.Stat(desktopDest); err == nil {
			_ = runGioSet(desktopDest, "metadata::trusted", "true")
		}
	}

	// Update desktop database if available
	if runtime.GOOS == "linux" {
		_ = runUpdateDesktopDatabase(appsDir)
	}

	return nil
}

// runGioSet runs `gio set <file> <key> <value>` silently (non-fatal).
func runGioSet(file, key, value string) error {
	// Create a logger for this operation
	logger, err := core.NewLogger("")
	if err != nil {
		return err
	}
	defer logger.Close()
	return core.RunCommand(core.RunModeSilent, []string{"gio", "set", file, key, value}, logger, "")
}

// runUpdateDesktopDatabase runs `update-desktop-database <dir>` silently (non-fatal).
func runUpdateDesktopDatabase(dir string) error {
	// Create a logger for this operation
	logger, err := core.NewLogger("")
	if err != nil {
		return err
	}
	defer logger.Close()
	return core.RunCommand(core.RunModeSilent, []string{"update-desktop-database", dir}, logger, "")
}

// copyFile copies a file from src to dst
func copyFile(src, dst string) error {
	source, err := os.Open(src)
	if err != nil {
		return fmt.Errorf("failed to open source file: %w", err)
	}
	defer source.Close()

	destination, err := os.Create(dst)
	if err != nil {
		return fmt.Errorf("failed to create destination file: %w", err)
	}
	defer destination.Close()

	_, err = destination.ReadFrom(source)
	return err
}

// GenerateLaunchVarsAMD creates the launch variables file for AMD GPUs.
// Writes to ${WINEPREFIX}/launch_vars.env (matching bash behavior).
// isFSR41: true if using FSR 4.1 upgrade path, false for regular mode
func GenerateLaunchVarsAMD(wineprefix string, isFSR41 bool) error {
	return writeLaunchVars(wineprefix, "AMD", isFSR41)
}

// GenerateLaunchVarsFileNvidia creates the launch variables file for NVIDIA GPUs.
// Writes to ${WINEPREFIX}/launch_vars.env (matching bash behavior).
func GenerateLaunchVarsFileNvidia(wineprefix string) error {
	return writeLaunchVars(wineprefix, "NVIDIA", false)
}

// writeLaunchVars creates the launch_vars.env file in the WINEPREFIX.
// The bash version writes this as a plain file (not in a subdirectory).
func writeLaunchVars(wineprefix, gpuType string, isFSR41 bool) error {
	// Determine FSR4 values based on mode
	fsr4Upgrade := "1"
	fsr4Rdna3Upgrade := "1"
	if isFSR41 && gpuType == "AMD" {
		fsr4Upgrade = "4.1.0"
		fsr4Rdna3Upgrade = "4.1.0"
	}

	content := fmt.Sprintf(`# Bellum Launch Variables (%s)
# Auto-generated by Bellum Linux Installer

export __GAMESCOPE_INTEGRATION=""
export __GAMESCOPE_INTEGRATION_FORCE="0"
export __GAMESCOPE_INTEGRATION_GAMER_MODE="0"
export NVAPI_OVERRIDE_CONFIG=""
export NVVM_LIBDIR="${PROTONPATH}/nvvm/lib64"
export LD_LIBRARY_PATH="${PROTONPATH}/lib64:${LD_LIBRARY_PATH}"
`, gpuType)

	// Add FSR4 variables for AMD GPUs
	if gpuType == "AMD" {
		content += fmt.Sprintf(`
export FSR4_UPGRADE="%s"
export FSR4_RDNA3_UPGRADE="%s"
`, fsr4Upgrade, fsr4Rdna3Upgrade)
	}

	return os.WriteFile(filepath.Join(wineprefix, "launch_vars.env"), []byte(content), 0644)
}

// CopyIcon copies the launcher icon to the user's local icon directory
// (matching bash behavior: ~/.local/share/icons/hicolor/256x256/apps/bellum.png)
func CopyIcon(iconPath string) error {
	if iconPath == "" {
		return fmt.Errorf("icon path is empty")
	}

	homeDir, err := os.UserHomeDir()
	if err != nil {
		return fmt.Errorf("failed to get user home directory: %w", err)
	}

	iconDest := filepath.Join(homeDir, ".local", "share", "icons", "hicolor", "256x256", "apps", "bellum.png")
	if err := os.MkdirAll(filepath.Dir(iconDest), 0755); err != nil {
		return fmt.Errorf("failed to create icon directory: %w", err)
	}

	return copyFile(iconPath, iconDest)
}

// DetectLauncherBinary returns the launcher binary name for the given GPU type.
// Both AMD and NVIDIA use the same binary name "Bellum" — the difference is
// in the wrapper content (wine vs proton).
func DetectLauncherBinary(gpuType string) string {
	return "Bellum"
}

// IsLauncherInstalled checks if the launcher binary exists for the given GPU type.
func IsLauncherInstalled(gpuType string) bool {
	binary := DetectLauncherBinary(gpuType)
	if binary == "" {
		return false
	}
	path := filepath.Join("/usr/local/bin", binary)
	_, err := os.Stat(path)
	return err == nil
}

// LauncherBinaryPath returns the full path to the launcher binary for the given GPU type.
func LauncherBinaryPath(gpuType string) string {
	binary := DetectLauncherBinary(gpuType)
	if binary == "" {
		return ""
	}
	return filepath.Join("/usr/local/bin", binary)
}

// LauncherDesktopPath returns the full path to the .desktop file for the given GPU type.
func LauncherDesktopPath(gpuType string) string {
	homeDir, err := os.UserHomeDir()
	if err != nil {
		return ""
	}

	binary := DetectLauncherBinary(gpuType)
	if binary == "" {
		return ""
	}
	return filepath.Join(homeDir, ".local", "share", "applications", binary+".desktop")
}

// LauncherIconPath returns the full path to the launcher icon.
func LauncherIconPath(gpuType string) string {
	homeDir, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(homeDir, ".local", "share", "icons", "hicolor", "256x256", "apps", "bellum.png")
}

